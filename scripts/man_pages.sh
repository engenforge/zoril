#!/bin/sh
# scripts/man_pages.sh — Keep the committed man pages (doc/man/<page>.<n>) in step with their
# scdoc sources (doc/man/<page>.<n>.scd).
#
# The roff pages are committed so that installing Zoril never needs scdoc; scdoc is a developer
# tool. scdoc writes the date it ran into each page's .TH line, so a page's date is taken to be the
# date its content last changed: a page whose content is unchanged keeps the date it has, and only a
# changed or new page is written with today's date (or SOURCE_DATE_EPOCH's, which scdoc honours).
#
# Usage:
#   scripts/man_pages.sh render   # rewrite every page whose content differs from its source
#   scripts/man_pages.sh check    # fail when a page is missing, stale, or has no source
#
# Exit 0 = the pages match their sources (check) or are now written (render).

set -eu

case "$0" in */*) cd "${0%/*}/.." ;; *) cd .. ;; esac || exit 2

MODE="${1:-}"
case "$MODE" in
    render|check) ;;
    *) echo "usage: scripts/man_pages.sh render|check" >&2; exit 2 ;;
esac

. scripts/lib/scdoc_version.sh
# The committed pages are made by scdoc 1.11.5; an older (or missing) scdoc cannot say whether they are
# current, so `check` skips and `render`, which would write pages the wrong version made, refuses.
_found=$(scdoc_found) || _found=""
if [ -z "$_found" ]; then
    if [ "$MODE" = check ]; then
        echo "[SKIP] man-pages: scdoc not found; $SCDOC_MIN or newer is needed to check the committed pages"
        exit 0
    fi
    echo "[FAIL] man-pages: scdoc not found on PATH; $SCDOC_MIN or newer is needed to render the committed pages" >&2
    exit 1
elif scdoc_old "$_found"; then
    if [ "$MODE" = check ]; then
        echo "[SKIP] man-pages: scdoc $_found is older than $SCDOC_MIN"
        exit 0
    fi
    echo "[FAIL] man-pages: scdoc $_found is older than $SCDOC_MIN, the version the committed pages are generated with; refusing to render" >&2
    exit 1
fi

MAN_DIR=doc/man
TMP_DIR="$(mktemp -d "${TMPDIR:-/tmp}/man_pages_XXXXXX")"
trap 'rm -rf "$TMP_DIR"' EXIT INT TERM

# The page with its .TH date replaced by a fixed word and its "Generated by scdoc <version>" line without
# the version, so two renderings compare by content: those two lines change with the day a page is made
# and with newer scdoc releases, and nothing else is ignored.
without_date() {
    sed -e '/^\.TH /s/^\(\.TH "[^"]*" "[^"]*" \)"[^"]*"/\1"DATE"/' \
        -e 's/^\(\.\\" Generated by scdoc\) .*/\1/' "$1"
}

status=0
for scd in "$MAN_DIR"/*.scd; do
    [ -f "$scd" ] || continue
    page="${scd%.scd}"
    fresh="$TMP_DIR/$(basename "$page")"
    if ! scdoc < "$scd" > "$fresh" 2> "$fresh.err" || [ -s "$fresh.err" ]; then
        echo "[FAIL] man-pages: scdoc failed or warned on $scd:" >&2
        cat "$fresh.err" >&2
        exit 1
    fi
    if [ -f "$page" ]; then
        without_date "$page" > "$fresh.old"
        without_date "$fresh" > "$fresh.new"
        cmp -s "$fresh.old" "$fresh.new" && continue
    fi
    if [ "$MODE" = render ]; then
        cp -f "$fresh" "$page"
        echo "wrote $page"
    elif [ -f "$page" ]; then
        echo "[FAIL] man-pages: $page does not match $scd; run make man" >&2
        diff -u "$fresh.old" "$fresh.new" | head -20 >&2 || true
        status=1
    else
        echo "[FAIL] man-pages: $page is missing; run make man" >&2
        status=1
    fi
done

# A committed page with no source would be installed and never checked.
for page in "$MAN_DIR"/*.[0-9]; do
    [ -f "$page" ] || continue
    [ -f "$page.scd" ] && continue
    echo "[FAIL] man-pages: $page has no source $page.scd" >&2
    status=1
done

exit $status
