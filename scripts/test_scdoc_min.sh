#!/bin/sh
# scripts/test_scdoc_min.sh — scdoc 1.11.5 is the minimum for checking the committed man pages.
#
# The pages in doc/man/ are generated with scdoc 1.11.5, and other releases write other roff for the
# same source (paragraph macros, list markup, hyphen escapes), so a page can only be compared with a
# rendering made by 1.11.5 or newer. Asserted here, with stub `scdoc` programs first on PATH that
# report a chosen version and otherwise copy stdin to stdout:
#
#   1. scripts/check_deps.sh: with scdoc 1.11.2 the `test` profile exits 0 and lists scdoc under
#      "Skipping optional test items:"; the `man` and `preflight` profiles exit 1 naming the version
#      found and the minimum. With 1.11.5 all three accept it.
#   2. scripts/man_pages.sh check: with 1.11.2 it prints "[SKIP] man-pages: scdoc 1.11.2 is older than
#      1.11.5" and exits 0 even for a stale page; with 1.11.5 it runs (a stale page fails, a current
#      one passes). `render` with 1.11.2 fails, naming both versions.
#   3. scripts/test_man_pages.sh skips the same way.
#   4. The comparison ignores the .TH date and the "Generated by scdoc" version, and nothing else:
#      "\-" against "-" is a difference, since 1.11.5 is the version the pages were made with.
#
# Usage: test_scdoc_min.sh      (no arguments)
set -u
cd "$(dirname "$0")/.." || exit 2
REPO_ROOT=$(pwd)

tmp="$(mktemp -d "${TMPDIR:-/tmp}/test_scdoc_min_XXXXXX")"
trap 'rm -rf "$tmp"' EXIT INT TERM

failed=0
pass() { echo "[PASS] scdoc-min: $*"; }
fail() { echo "[FAIL] scdoc-min: $*"; failed=1; }

# stub VERSION — a directory holding an scdoc that reports VERSION and copies stdin otherwise
stub() {
    mkdir -p "$tmp/stub-$1"
    cat > "$tmp/stub-$1/scdoc" <<EOF
#!/bin/sh
if [ "\${1:-}" = -v ]; then echo "scdoc $1"; exit 0; fi
cat
EOF
    chmod +x "$tmp/stub-$1/scdoc"
}
stub 1.11.2
stub 1.11.5
stub 1.12.0

# run LABEL — runs the rest of the arguments, keeping output in $tmp/out and the status in $rc
run() { rc=0; "$@" > "$tmp/out" 2>&1 || rc=$?; }
has() { grep -qF -- "$1" "$tmp/out"; }

# ── 1. check_deps.sh ────────────────────────────────────────────────────────────
PATH="$tmp/stub-1.11.2:$PATH" run sh scripts/check_deps.sh test
if [ "$rc" -eq 0 ] && has "Skipping optional test items:" && has "scdoc 1.11.2"; then
    pass "check_deps test with scdoc 1.11.2: exit 0, scdoc listed under the skipped items"
else
    fail "check_deps test with scdoc 1.11.2 (exit $rc) should exit 0 and list scdoc as skipped:"; sed 's/^/       /' "$tmp/out"
fi
for profile in man preflight; do
    PATH="$tmp/stub-1.11.2:$PATH" run sh scripts/check_deps.sh "$profile"
    if [ "$rc" -eq 1 ] && has "1.11.2" && has "1.11.5"; then
        pass "check_deps $profile with scdoc 1.11.2: exit 1, names 1.11.2 and the minimum 1.11.5"
    else
        fail "check_deps $profile with scdoc 1.11.2 (exit $rc) should exit 1 naming 1.11.2 and 1.11.5:"; sed 's/^/       /' "$tmp/out"
    fi
done
for v in 1.11.5 1.12.0; do
    PATH="$tmp/stub-$v:$PATH" run sh scripts/check_deps.sh man
    if [ "$rc" -eq 0 ]; then
        pass "check_deps man accepts scdoc $v"
    else
        fail "check_deps man rejected scdoc $v (exit $rc):"; sed 's/^/       /' "$tmp/out"
    fi
done
PATH="$tmp/stub-1.11.5:$PATH" run sh scripts/check_deps.sh test
if [ "$rc" -eq 0 ] && ! has "scdoc"; then
    pass "check_deps test with scdoc 1.11.5 does not list scdoc as skipped"
else
    fail "check_deps test with scdoc 1.11.5 (exit $rc) should not mention scdoc:"; sed 's/^/       /' "$tmp/out"
fi

# ── 2. man_pages.sh, in a scratch tree (it works relative to its own checkout) ─
tree="$tmp/tree"
mkdir -p "$tree/scripts/lib" "$tree/doc/man"
cp scripts/man_pages.sh "$tree/scripts/"
cp scripts/lib/*.sh "$tree/scripts/lib/"
printf 'one paragraph\n' > "$tree/doc/man/x.1.scd"
printf 'a stale page\n' > "$tree/doc/man/x.1"

PATH="$tmp/stub-1.11.2:$PATH" run "$tree/scripts/man_pages.sh" check
if [ "$rc" -eq 0 ] && has "[SKIP] man-pages: scdoc 1.11.2 is older than 1.11.5"; then
    pass "man_pages.sh check with scdoc 1.11.2 skips (exit 0) even though the page is stale"
else
    fail "man_pages.sh check with scdoc 1.11.2 (exit $rc) should print the [SKIP] line and exit 0:"; sed 's/^/       /' "$tmp/out"
fi
PATH="$tmp/stub-1.11.2:$PATH" run "$tree/scripts/man_pages.sh" render
if [ "$rc" -ne 0 ] && has "1.11.2" && has "1.11.5" && [ "$(cat "$tree/doc/man/x.1")" = "a stale page" ]; then
    pass "man_pages.sh render with scdoc 1.11.2 fails, names both versions and writes nothing"
else
    fail "man_pages.sh render with scdoc 1.11.2 (exit $rc) should fail naming 1.11.2 and 1.11.5 and leave the page alone:"; sed 's/^/       /' "$tmp/out"
fi
printf 'a stale page\n' > "$tree/doc/man/x.1"
PATH="$tmp/stub-1.11.5:$PATH" run "$tree/scripts/man_pages.sh" check
if [ "$rc" -ne 0 ] && has "does not match"; then
    pass "man_pages.sh check with scdoc 1.11.5 runs: a stale page fails"
else
    fail "man_pages.sh check with scdoc 1.11.5 (exit $rc) should compare and fail on a stale page:"; sed 's/^/       /' "$tmp/out"
fi
printf 'one paragraph\n' > "$tree/doc/man/x.1"
PATH="$tmp/stub-1.11.5:$PATH" run "$tree/scripts/man_pages.sh" check
if [ "$rc" -eq 0 ]; then
    pass "man_pages.sh check with scdoc 1.11.5 passes a current page"
else
    fail "man_pages.sh check with scdoc 1.11.5 (exit $rc) should pass a current page:"; sed 's/^/       /' "$tmp/out"
fi

# ── 4. what the comparison ignores ──────────────────────────────────────────────
printf '.\\" Generated by scdoc 1.11.5\n.TH "x" "1" "2026-10-30"\nsome text\n' > "$tree/doc/man/x.1.scd"
printf '.\\" Generated by scdoc 1.12.0\n.TH "x" "1" "2027-01-02"\nsome text\n' > "$tree/doc/man/x.1"
PATH="$tmp/stub-1.11.5:$PATH" run "$tree/scripts/man_pages.sh" check
if [ "$rc" -eq 0 ]; then
    pass "the .TH date and the scdoc version in the generated-by line are ignored"
else
    fail "a different .TH date or generated-by version (exit $rc) should not count as a difference:"; sed 's/^/       /' "$tmp/out"
fi
printf 'a-b\n' > "$tree/doc/man/x.1.scd"
printf 'a\\-b\n' > "$tree/doc/man/x.1"
PATH="$tmp/stub-1.11.5:$PATH" run "$tree/scripts/man_pages.sh" check
if [ "$rc" -ne 0 ]; then
    pass '"\-" against "-" is a difference (the pages are made with 1.11.5, which writes one spelling)'
else
    fail '"\-" against "-" (exit '"$rc"') should be a difference, not ignored'
fi

# ── 3. test_man_pages.sh ────────────────────────────────────────────────────────
PATH="$tmp/stub-1.11.2:$PATH" run sh scripts/test_man_pages.sh
if [ "$rc" -eq 0 ] && has "[SKIP] man-pages: scdoc 1.11.2 is older than 1.11.5"; then
    pass "test_man_pages.sh with scdoc 1.11.2 skips (exit 0)"
else
    fail "test_man_pages.sh with scdoc 1.11.2 (exit $rc) should print the [SKIP] line and exit 0:"; tail -n 8 "$tmp/out" | sed 's/^/       /'
fi

if [ "$failed" -ne 0 ]; then
    echo "FAIL: scdoc 1.11.5 is not the minimum everywhere it should be."
    exit 1
fi
echo "PASS: scdoc 1.11.5 is the minimum for the man page checks."
